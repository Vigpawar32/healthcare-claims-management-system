USE healthcare_claims;

INSERT INTO claims
(patient_id, provider_id, payer_id, claim_number,
service_date, claim_amount, claim_status)
SELECT
p.patient_id,
pr.provider_id,
ip.payer_id,
CONCAT('CLM', 2000 + n.n),
DATE_ADD('2026-09-01', INTERVAL n.n DAY),
CASE
WHEN MOD(n.n, 5) = 0 THEN 5500.00
WHEN MOD(n.n, 5) = 1 THEN 1200.00
WHEN MOD(n.n, 5) = 2 THEN 3200.00
WHEN MOD(n.n, 5) = 3 THEN 750.00
ELSE 2400.00
END,
CASE
WHEN MOD(n.n, 4) = 0 THEN 'Submitted'
WHEN MOD(n.n, 4) = 1 THEN 'In Progress'
WHEN MOD(n.n, 4) = 2 THEN 'Paid'
ELSE 'Denied'
END
FROM
(
SELECT 1 AS n UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL
SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL
SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL
SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12 UNION ALL
SELECT 13 UNION ALL SELECT 14 UNION ALL SELECT 15 UNION ALL
SELECT 16 UNION ALL SELECT 17 UNION ALL SELECT 18 UNION ALL
SELECT 19 UNION ALL SELECT 20 UNION ALL SELECT 21 UNION ALL
SELECT 22 UNION ALL SELECT 23 UNION ALL SELECT 24 UNION ALL
SELECT 25 UNION ALL SELECT 26 UNION ALL SELECT 27 UNION ALL
SELECT 28 UNION ALL SELECT 29 UNION ALL SELECT 30 UNION ALL
SELECT 31 UNION ALL SELECT 32 UNION ALL SELECT 33 UNION ALL
SELECT 34 UNION ALL SELECT 35 UNION ALL SELECT 36 UNION ALL
SELECT 37
) AS n
CROSS JOIN (
SELECT patient_id,
ROW_NUMBER() OVER (ORDER BY patient_id) AS rn
FROM patients
) AS p
CROSS JOIN (
SELECT provider_id,
ROW_NUMBER() OVER (ORDER BY provider_id) AS rn
FROM providers
) AS pr
CROSS JOIN (
SELECT payer_id,
ROW_NUMBER() OVER (ORDER BY payer_id) AS rn
FROM insurance_payers
) AS ip
WHERE p.rn = MOD(n.n - 1, 20) + 1
  AND pr.rn = MOD(n.n - 1, 8) + 1
  AND ip.rn = MOD(n.n - 1, 10) + 1;

SELECT COUNT(*) AS total_claims
FROM claims;
